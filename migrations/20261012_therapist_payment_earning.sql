CREATE TABLE IF NOT EXISTS therapist_payment_earning (
    id INT NOT NULL AUTO_INCREMENT,
    payment_id BIGINT NOT NULL,
    patient_slot_booking_id INT NOT NULL,
    therapist_id INT NOT NULL,
    program_id INT NOT NULL,
    config_id INT NOT NULL,
    earning_date DATE NOT NULL,
    received_amount FLOAT NOT NULL DEFAULT 0,
    gst_amount FLOAT NOT NULL DEFAULT 0,
    amount_after_gst FLOAT NOT NULL DEFAULT 0,
    therapist_amount FLOAT NOT NULL DEFAULT 0,
    organization_amount FLOAT NOT NULL DEFAULT 0,
    calculation_json TEXT NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'eligible',
    monthly_payout_id INT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_payment_therapist_earning (payment_id, therapist_id),
    KEY ix_payment_earning_date (earning_date),
    KEY ix_payment_earning_therapist (therapist_id),
    KEY ix_payment_earning_monthly (monthly_payout_id),
    CONSTRAINT fk_payment_earning_payment FOREIGN KEY (payment_id) REFERENCES payments(id),
    CONSTRAINT fk_payment_earning_booking FOREIGN KEY (patient_slot_booking_id) REFERENCES patient_slot_booking(id),
    CONSTRAINT fk_payment_earning_therapist FOREIGN KEY (therapist_id) REFERENCES therapists(id),
    CONSTRAINT fk_payment_earning_program FOREIGN KEY (program_id) REFERENCES programs(id),
    CONSTRAINT fk_payment_earning_config FOREIGN KEY (config_id) REFERENCES program_payment_config(id),
    CONSTRAINT fk_payment_earning_monthly FOREIGN KEY (monthly_payout_id) REFERENCES therapist_monthly_payout(id)
);